/**
 * Regenerate `template.lock.json`. RUN IN THE TEMPLATE, never in a shop.
 *
 * The lock is what a storefront carries so it can answer two questions without
 * having the template checked out beside it:
 *
 *   locked    the bytes this shop agreed not to change. `audit:template` fails
 *             on any mismatch — that is drift, and drift in shared code is how
 *             one shop quietly stops getting everyone else's bug fixes.
 *   baseline  the bytes the shop's OWN files started from. Never enforced. It
 *             exists so the template can later ask "have I fixed something in
 *             the home page that this shop forked before?" — see
 *             scripts/template-report.mjs.
 *
 * Running this in a shop would stamp that shop's own commit and re-bless
 * whatever it had changed, which is why the file records the origin URL it was
 * generated from: a lock claiming to come from a storefront repo is visibly
 * wrong in review.
 */
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  UNLOCKED,
  LOCK_FILE,
  CORE_TIER,
  PRESENTATION_TIER,
  lockedFiles,
  hashFile,
  tierOf,
} from './template-lock.mjs';

const root = process.cwd();

function git(...args) {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

/**
 * `{ hash, tier }` per file, not a bare hash.
 *
 * The tier is written INTO the lock rather than derived where it is read,
 * because the lock is the thing a storefront carries. Deriving it in the audit
 * would work exactly as well today and would silently re-classify every file in
 * every shop the day the template moves a directory — each shop taking the new
 * classification along with the scripts, none of them seeing it. Written here,
 * a re-tiering is a line in `template.lock.json` that a reviewer reads.
 */
const locked = {};
for (const rel of await lockedFiles(root)) {
  locked[rel] = { hash: await hashFile(root, rel), tier: tierOf(rel) };
}

const tally = (tier) => Object.values(locked).filter((entry) => entry.tier === tier).length;

const baseline = {};
for (const rel of UNLOCKED) {
  baseline[rel] = await hashFile(root, rel);
}

const lock = {
  /* The leading marker is load-bearing: audit-brand.mjs skips root files that
     declare themselves generated, and this one records the template's origin
     URL — which carries an organisation name that the extraction-residue check
     would otherwise read as the original shop surviving a fork. The URL is
     worth keeping: it is what makes a lock generated inside a storefront, and
     therefore self-blessing, visible in review. */
  $comment:
    'GENERATED by scripts/write-template-lock.mjs, in the TEMPLATE. `locked` is ' +
    'checked byte-for-byte by npm run audit:template — `core` always, `presentation` ' +
    'unless this shop names the file in brand/unlock.ts. `baseline` is advisory: it ' +
    'records what this shop\'s own files started from, so the template can report ' +
    'later fixes it has that the shop does not. See README -> Template boundary.',
  template: {
    origin: git('remote', 'get-url', 'origin'),
    commit: git('rev-parse', 'HEAD'),
  },
  locked,
  baseline,
};

await writeFile(path.join(root, LOCK_FILE), JSON.stringify(lock, null, 2) + '\n', 'utf8');
console.log(
  `template.lock.json written: ${Object.keys(locked).length} locked file(s) ` +
    `(${tally(CORE_TIER)} ${CORE_TIER} / ${tally(PRESENTATION_TIER)} ${PRESENTATION_TIER}), ` +
    `${Object.keys(baseline).length} baseline file(s), at ${lock.template.commit.slice(0, 7) || 'unknown'}.`
);
